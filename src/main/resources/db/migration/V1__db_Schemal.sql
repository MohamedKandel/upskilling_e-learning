CREATE INDEX idx_sessions_course_order
    ON sessions (crs_id, session_order);

CREATE INDEX idx_sessions_status
    ON sessions (status);


CREATE INDEX idx_enrollment_crs_id
    ON enrollment (crs_id);

CREATE INDEX idx_done_sessions_student
    ON done_sessions (student_id);

CREATE INDEX idx_done_sessions_student_completed
    ON done_sessions (student_id, is_completed);
CREATE INDEX idx_courses_name
    ON courses (crs_name);
CREATE INDEX idx_students_phone
    ON students (phone);